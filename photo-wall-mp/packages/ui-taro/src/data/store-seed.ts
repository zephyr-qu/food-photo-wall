/**
 * 会话级封面种子：照片墙上每格显示该记录多张照片里的**随机一张**。
 *
 *  为什么用种子而不是每次 Math.random()：墙上每格要在整个会话里保持同一张，
 *  否则用户滑动时图片在变（看着像加载错乱）。种子在模块加载时定一次，
 *  之后由 pickCover 按「种子 + 记录 id」哈希决定 —— 随机但可复现。
 *
 *  ⚠ 列表类加载（首屏 / 翻页 / 跳月 / 店铺）才用它；
 *  详情页不传种子 —— 详情页的封面必须是 photos[0]（用户选的第一张）。
 */
export const COVER_SEED = Math.random().toString(36).slice(2, 10);
